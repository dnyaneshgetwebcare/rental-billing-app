export type MessageKey = keyof typeof STRINGS.en;

interface I18nState {
  lang: Lang;
  setLang(lang: Lang): void;
  t(key: MessageKey): string;
}

const I18nContext = createContext<I18nState | null>(null);
const STORAGE_KEY = 'rb_lang';

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem(STORAGE_KEY) === 'mr' ? 'mr' : 'en'));
  const setLang = (next: Lang) => {
    localStorage.setItem(STORAGE_KEY, next);
    setLangState(next);
  };
  useEffect(() => {
    document.documentElement.lang = lang === 'mr' ? 'mr' : 'en';
  }, [lang]);
  const value = useMemo<I18nState>(() => ({
    lang,
    setLang,
    t(key) {
      return STRINGS[lang][key] ?? STRINGS.en[key];
    },
  }), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n outside I18nProvider');
  return ctx;
}

export function LanguageSwitch() {
  const { lang, setLang } = useI18n();
  return (
    <div className="lang-switch" role="group" aria-label="Language">
      <button type="button" className={lang === 'en' ? 'on' : ''} onClick={() => setLang('en')}>EN</button>
      <button type="button" className={lang === 'mr' ? 'on' : ''} onClick={() => setLang('mr')}>मराठी</button>
    </div>
  );
}
